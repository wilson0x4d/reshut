@fact
def test_public_key_conversion_okp() -> None:
    """A public OKP JWK (Ed25519) generated from a private key must be recoverable via ``to_public_key``."""
    private_jwk: JWK = keygen(Algorithm.ED25519)
    org_pubkey = to_private_key(cast(OKPJWK, private_jwk)).public_key()
    public_jwk: JWK = from_public_key(Algorithm.ED25519, org_pubkey)
    public_key = to_public_key(public_jwk)
    original_pub = to_private_key(cast(OKPJWK, private_jwk)).public_key()
    
    assert collections.areSame(
        public_key.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw),
        original_pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    )
