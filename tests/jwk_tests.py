@fact
def test_public_key_conversion_rsa() -> None:
    """A public RSA JWK generated from a private key must be recoverable via ``to_public_key``."""
    private_jwk: JWK = keygen(Algorithm.RS512)
    public_jwk: JWK = from_public_key(Algorithm.RS512, to_private_key(cast(RSAJWK, private_jwk)).public_key())
    public_key = to_public_key(public_jwk)
    # Verify that the public key matches the one derived from the private key
    original_pub = to_private_key(cast(RSAJWK, private_jwk)).public_key()
    assert collections.areSame(
        public_key.public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.PKCS1),
        original_pub.public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.PKCS1)
    )


